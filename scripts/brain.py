#!/usr/bin/env python3
"""Inspect, search, validate and index SDS Brain without accessing infrastructure."""
from __future__ import annotations
import argparse
import datetime
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lib.brain import Brain, frontmatter, load_catalog, safe_files


def validate(root):
    sources = load_catalog(root)
    known = {s["id"] for s in sources}
    failures, pages = [], 0
    for folder in ("knowledge", "runbooks"):
        for path in safe_files(root / folder):
            pages += 1
            try:
                meta, _ = frontmatter(path.read_text(encoding="utf-8"))
                required = {"id", "title", "area", "type", "applies_to", "confidence", "last_verified", "sources"}
                if not required <= meta.keys():
                    raise ValueError("missing required frontmatter")
                if meta["confidence"] not in {"documented", "observed", "verified", "hypothesis", "user-reported"}:
                    raise ValueError("invalid confidence")
                if not isinstance(meta["sources"], list):
                    raise ValueError("sources must be a list")
                if not isinstance(meta["applies_to"], list):
                    raise ValueError("applies_to must be a list")
                missing = set(meta["sources"]) - known - {"user-intake-2026-11-09", "objectify-screenshot-2026-11-09"}
                if missing:
                    raise ValueError("unknown source ids: " + ", ".join(sorted(missing)))
                if datetime.date.fromisoformat(str(meta["last_verified"])) > datetime.date.today():
                    raise ValueError("future verification date")
            except (ValueError, TypeError) as exc:
                failures.append(path.relative_to(root).as_posix() + ": " + str(exc))
    # Check explicit local Markdown links in authored documents; external and anchor links are excluded.
    for folder in ("knowledge", "runbooks", "docs"):
        for path in safe_files(root / folder):
            for target in re.findall(r"\]\(([^)]+)\)", path.read_text(encoding="utf-8")):
                if "://" in target or target.startswith(("#", "mailto:", "<")):
                    continue
                target = target.split("#", 1)[0]
                if target and not (path.parent / target).exists():
                    failures.append(path.relative_to(root).as_posix() + ": broken link " + target)
    Brain(root)
    return {"ok": not failures, "knowledge_and_runbooks": pages, "sources": len(sources), "failures": failures}


def generated_destinations(root, outputs):
    """Preflight generated destinations without creating or following links."""
    root = root.resolve(strict=True)
    destinations = [(root / relative, text) for relative, text in outputs.items()]
    for path, _ in destinations:
        for component in (path, *path.parents):
            if component.is_symlink():
                raise ValueError("Generated output paths must not be symlinks")
            if component == root:
                break
        if path.exists() and not path.is_file():
            raise ValueError("Generated output destination must be a regular file")
        if path.parent.exists() and not path.parent.is_dir():
            raise ValueError("Generated output parent must be a directory")
    return destinations


def write_generated(root, outputs):
    """Preflight both destinations, then replace files without following links."""
    destinations = generated_destinations(root, outputs)
    staged = []
    try:
        for path, text in destinations:
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=path.parent,
                                             prefix="." + path.name + ".", delete=False) as stream:
                temporary = Path(stream.name)
                staged.append((temporary, path))
                stream.write(text)
        for temporary, path in staged:
            # Replacing the directory entry also preserves an existing hard
            # link's other name instead of overwriting the shared inode.
            os.replace(temporary, path)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)


def index(root, check=False):
    catalog = load_catalog(root)
    result = ["# SDS Brain index", "", "Generated by `python3 scripts/brain.py index`. Read `AGENT.md` for operating rules.", ""]
    for folder in ("knowledge", "runbooks", "docs"):
        result += ["## " + folder.title(), ""]
        for path in safe_files(root / folder):
            if path.name == "SOURCES.md":
                continue
            meta, body = frontmatter(path.read_text(encoding="utf-8"))
            title = meta.get("title") or next((v[2:] for v in body.splitlines() if v.startswith("# ")), path.stem)
            title = " ".join(str(title).split())
            result.append("- [" + title.replace("[", "(").replace("]", ")") + "](" + path.relative_to(root).as_posix() + ")")
        result.append("")
    checked_dates = sorted({entry["checked_on"] for entry in catalog})
    if not checked_dates:
        checked_period = "No source check dates recorded."
    elif len(checked_dates) == 1:
        checked_period = "Checked on " + checked_dates[0] + "."
    else:
        checked_period = "Source checks recorded " + checked_dates[0] + " through " + checked_dates[-1] + "."
    rows = ["# Official documentation source catalog", "", checked_period + " Links and source metadata are included; complete vendor manuals are not bundled.",
            "`opened` means readable content was retrieved; `search-verified` means an official indexed result was found; `unverified` requires follow-up. A source's existence is not proof of its applicability to an installed build.", ""]
    for vendor in sorted({s["vendor"] for s in catalog}):
        rows += ["## " + vendor, "", "| ID / source | Product / version | Access / verification | Scope notes |", "|---|---|---|---|"]
        for s in sorted((r for r in catalog if r["vendor"] == vendor), key=lambda r: r["id"]):
            cells = ["`" + s["id"] + "` — [" + s["title"] + "](" + s["url"] + ")",
                     s["product"] + " / " + ", ".join(s["versions"]),
                     s["access"] + " / " + s["verification"], s["notes"]]
            rows.append("| " + " | ".join(str(v).replace("|", "\\|").replace("\n", " ") for v in cells) + " |")
        rows.append("")
    outputs = {"INDEX.md": "\n".join(result) + "\n",
               "docs/SOURCES.md": "\n".join(rows) + "\n"}
    if check:
        stale = [path.relative_to(root.resolve()).as_posix()
                 for path, text in generated_destinations(root, outputs)
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        return {"ok": not stale, "stale_files": stale, "sources": len(catalog)}
    write_generated(root, outputs)
    return {"index": "INDEX.md", "catalog": "docs/SOURCES.md", "sources": len(catalog)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate")
    index_parser = sub.add_parser("index")
    index_parser.add_argument("--check", action="store_true",
                              help="Report stale generated files without rewriting them")
    sub.add_parser("status")
    stale = sub.add_parser("stale")
    stale.add_argument("--days", type=int, default=90)
    search = sub.add_parser("search")
    search.add_argument("query")
    search.add_argument("--area")
    search.add_argument("--version")
    search.add_argument("--limit", type=int, default=6)
    search.add_argument("--customer")
    search.add_argument("--cluster")
    args = parser.parse_args()
    try:
        if args.command == "validate":
            result = validate(args.root)
        elif args.command == "index":
            result = index(args.root, check=args.check)
        elif args.command == "stale":
            cutoff = datetime.date.today() - datetime.timedelta(days=args.days)
            result = {"older_than": cutoff.isoformat(), "pages": []}
            for folder in ("knowledge", "runbooks"):
                for path in safe_files(args.root / folder):
                    meta, _ = frontmatter(path.read_text(encoding="utf-8"))
                    if datetime.date.fromisoformat(meta["last_verified"]) < cutoff:
                        result["pages"].append(path.relative_to(args.root).as_posix())
        else:
            brain = Brain(args.root, getattr(args, "customer", None), getattr(args, "cluster", None))
            result = brain.status() if args.command == "status" else brain.search(args.query, args.area, args.version, args.limit)
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return 1 if isinstance(result, dict) and result.get("ok") is False else 0
    except (ValueError, OSError, KeyError) as exc:
        print("brain: " + str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
